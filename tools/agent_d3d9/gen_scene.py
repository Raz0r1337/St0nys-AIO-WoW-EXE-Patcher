# Generates scene.h (figure geometry) and shaders.h (shader DWORDs) for glowtest.c.
# Figure 1 (category 1): exact mask of glowsim/sim.py figure(), as pixel-aligned rectangles,
#   placed at (OX, OY) (even offsets so the half-resolution 2x2 grid matches the simulation).
# Figure 2 (category 2): a circle polygon with sub-pixel centre (exercises MSAA edge samples).
import sys, os, math, struct
S = '/tmp/claude-0/-home-user-St0nys-WoW-EXE-Patcher/49e16a66-3a63-5e77-ae4f-92ef019273b7/scratchpad'
OUT = os.path.join(S, 'agent_d3d9')
sys.path.insert(0, os.path.join(S, 'glowsim')); sys.path.insert(0, os.path.join(S, 'ol2'))
import numpy as np
import sim, psasm

OX, OY = 40, 60
C2X, C2Y, C2R, C2N = 515.3, 250.6, 55.0, 48

def rects_from_mask(m):
    rects, open_ = [], {}
    for y in range(m.shape[0]):
        row = m[y]; runs = []; x = 0
        while x < m.shape[1]:
            if row[x]:
                x0 = x
                while x < m.shape[1] and row[x]: x += 1
                runs.append((x0, x))
            else:
                x += 1
        new = {}
        for r in runs:
            if r in open_:
                rects[open_[r]][3] = y + 1; new[r] = open_[r]
            else:
                rects.append([r[0], y, r[1], y + 1]); new[r] = len(rects) - 1
        open_ = new
    return rects

fig = sim.figure()
rects = rects_from_mask(fig)
chk = np.zeros_like(fig)
for x0, y0, x1, y1 in rects: chk[y0:y1, x0:x1] = True
assert (chk == fig).all()

with open(os.path.join(OUT, 'scene.h'), 'w') as f:
    f.write('/* generated by gen_scene.py */\n')
    f.write('#define FIG1_OX %d\n#define FIG1_OY %d\n#define FIG1_NRECT %d\n' % (OX, OY, len(rects)))
    f.write('static const short fig1_rects[FIG1_NRECT][4] = {\n')
    for r in rects: f.write('  {%d,%d,%d,%d},\n' % tuple(r))
    f.write('};\n')
    f.write('#define FIG2_CX %.4ff\n#define FIG2_CY %.4ff\n#define FIG2_R %.4ff\n#define FIG2_N %d\n' % (C2X, C2Y, C2R, C2N))

g = psasm.blur_ps(0.2270270, 0.3162162, 0.0702703); c = psasm.comp_ps(4.0)
assert len(g) == 284 and len(c) == 100
def arr(name, b):
    d = struct.unpack('<%dI' % (len(b) // 4), b)
    s = 'static const DWORD %s[%d] = {\n' % (name, len(d))
    for i in range(0, len(d), 6): s += '  ' + ', '.join('0x%08X' % x for x in d[i:i + 6]) + ',\n'
    return s + '};\n'
with open(os.path.join(OUT, 'shaders.h'), 'w') as f:
    f.write('/* generated by gen_scene.py from ol2/psasm.py: blur_ps(0.2270270,0.3162162,0.0702703), comp_ps(4.0) */\n')
    f.write('/* blur %s */\n/* comp %s */\n' % (g.hex(), c.hex()))
    f.write(arr('GPSCODE', g)); f.write(arr('CPSCODE', c))
    f.write('static const DWORD RINGPSCODE[5] = { 0xFFFF0101, 0x00000001, 0x800F0000, 0x90E40000, 0x0000FFFF };\n')
