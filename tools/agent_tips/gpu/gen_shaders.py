# gen_shaders.py - tips_shaders.h (C arrays) and .bin/.asm pairs for shadercheck from agent_tips/gen_fix/psasm.py
import os, sys, struct
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.join(os.path.dirname(HERE), 'gen_fix'))
import psasm as p, outline10 as o
SH = dict(GPSCODE=p.blur_ps(*o.BLUR_W), CPSCODE=p.comp_ps(1.0), TPSCODE=p.tent_ps(), VPSOLD=p.blur_soft_ps(*o.BLUR_W, 2.5),
          VPSNEW=p.blur_soft_ps(*o.BLUR_W, o.GLOW_K), LPSCODE=p.line_ps(o.LINE_K), LCPSCODE=p.linecomp_ps(),
          RINGPSCODE=struct.pack('<5I', 0xFFFF0101, 0x00000001, 0x800F0000, 0x90E40000, 0x0000FFFF))
with open(os.path.join(HERE, 'tips_shaders.h'), 'w') as f:
    f.write('/* generated by gen_shaders.py from agent_tips/gen_fix/psasm.py (GLOW_K new %g, LINE_K %g) */\n' % (o.GLOW_K, o.LINE_K))
    for k, b in SH.items():
        w = struct.unpack('<%dI' % (len(b) // 4), b)
        f.write('static const DWORD %s[] = {%s};\n' % (k, ', '.join('0x%08X' % x for x in w)))
for k in ('LPSCODE', 'LCPSCODE', 'VPSNEW'):
    open(os.path.join(HERE, k + '.bin'), 'wb').write(SH[k])
    lines = p.disasm(SH[k])[:-1]
    w = struct.unpack('<%dI' % (len(SH[k]) // 4), SH[k]); i = 1; defs = []
    while i < len(w) and w[i] != 0xFFFF:   # def constants with 9 digits (the 7 of psasm.disasm are not exact for the assembler)
        n = (w[i] >> 24) & 0xF
        if w[i] & 0xFFFF == 0x51: defs.append(', '.join('%.9g' % struct.unpack('<f', struct.pack('<I', x))[0] for x in w[i + 2:i + 2 + 4]))
        i += 1 + n
    j = 0
    for li, l in enumerate(lines):
        if l.startswith('def '): lines[li] = l.split(',')[0] + ', ' + defs[j]; j += 1
    txt = '\n'.join(lines) + '\n'
    open(os.path.join(HERE, k + '.asm'), 'w').write(txt)
print('ok', {k: len(v) for k, v in SH.items()})
